import "server-only";
import { randomBytes } from "node:crypto";
import type { TokenCredential } from "@azure/identity";
import { z } from "zod";
import { AppError, ConfigurationError } from "../errors";
import { readBinaryBody } from "../request-body";

export interface EntraDirectoryOptions {
  tenantId: string;
  tenantSubdomain: string;
  timeoutMs?: number;
}
export interface EntraDirectoryAccount {
  objectId: string;
  subject: string;
  email: string;
}
class DirectoryFault extends Error {
  constructor(
    readonly kind: "unavailable" | "conflict" | "limited" | "rejected",
  ) {
    super(kind);
  }
}
const userSchema = z.object({
  id: z.uuid(),
  accountEnabled: z.literal(true),
  userType: z.literal("Member"),
  identities: z
    .array(
      z.object({
        signInType: z.string().min(1).max(32),
        issuer: z.string().min(1).max(253),
        issuerAssignedId: z.string().min(1).max(320),
      }),
    )
    .min(1)
    .max(20),
});
const graph = "https://graph.microsoft.com/v1.0/users";
const select = "id,accountEnabled,userType,identities";

/** Narrow public-Azure customer directory API. No retries, generic endpoints or mail. */
export class EntraDirectoryUsers {
  private readonly tenantId: string;
  private readonly issuer: string;
  private readonly timeoutMs: number;
  constructor(
    options: EntraDirectoryOptions,
    private readonly credential: TokenCredential,
    private readonly request: typeof fetch = fetch,
    private readonly now: () => number = Date.now,
  ) {
    if (
      !z.uuid().safeParse(options.tenantId).success ||
      !/^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/.test(options.tenantSubdomain)
    )
      throw new ConfigurationError(["ENTRA_DIRECTORY_AUTHORITY"]);
    this.tenantId = options.tenantId.toLowerCase();
    this.issuer = `${options.tenantSubdomain}.onmicrosoft.com`;
    this.timeoutMs = options.timeoutMs ?? 10000;
    if (
      !Number.isInteger(this.timeoutMs) ||
      this.timeoutMs < 1 ||
      this.timeoutMs > 20000
    )
      throw new ConfigurationError(["ENTRA_DIRECTORY_TIMEOUT"]);
  }
  private email(value: string) {
    if (
      typeof value !== "string" ||
      value !== value.trim() ||
      value.length > 254 ||
      !z.email().safeParse(value).success
    )
      throw new AppError(
        "INVALID_DIRECTORY_REQUEST",
        "Enter valid account details.",
        422,
      );
    return value.toLowerCase();
  }
  private account(
    value: unknown,
    email: string,
    objectId?: string,
  ): Readonly<EntraDirectoryAccount> {
    const result = userSchema.safeParse(value);
    if (!result.success) throw new DirectoryFault("unavailable");
    const user = result.data,
      id = user.id.toLowerCase();
    const matches = user.identities.filter(
      (identity) =>
        identity.signInType === "emailAddress" &&
        identity.issuer.toLowerCase() === this.issuer &&
        identity.issuerAssignedId.toLowerCase() === email,
    );
    if (matches.length !== 1 || (objectId !== undefined && id !== objectId))
      throw new DirectoryFault("conflict");
    return Object.freeze({
      objectId: id,
      subject: `${this.tenantId}:${id}`,
      email,
    });
  }
  private async run<T>(
    work: (
      send: (
        url: string,
        method: "GET" | "POST",
        body?: string,
      ) => Promise<unknown>,
      state: { writeMayHaveCommitted: boolean },
    ) => Promise<T>,
  ): Promise<T> {
    const controller = new AbortController(),
      state = { writeMayHaveCommitted: false };
    let timer: ReturnType<typeof setTimeout> | undefined;
    try {
      return await Promise.race([
        (async () => {
          const token = await this.credential.getToken(
            "https://graph.microsoft.com/.default",
            { abortSignal: controller.signal },
          );
          controller.signal.throwIfAborted();
          const now = this.now();
          if (
            !Number.isSafeInteger(now) ||
            now <= 0 ||
            !token ||
            typeof token.token !== "string" ||
            !/^[\x21-\x7e]{1,16384}$/.test(token.token) ||
            !Number.isSafeInteger(token.expiresOnTimestamp) ||
            token.expiresOnTimestamp <= now + 30000
          )
            throw new DirectoryFault("unavailable");
          const send = async (
            url: string,
            method: "GET" | "POST",
            body?: string,
          ) => {
            controller.signal.throwIfAborted();
            // Only URLs generated by the fixed public methods are passed here.
            if (method === "POST") state.writeMayHaveCommitted = true;
            const response = await this.request(url, {
              method,
              headers: {
                Authorization: `Bearer ${token.token}`,
                Accept: "application/json",
                ...(body === undefined
                  ? {}
                  : { "Content-Type": "application/json" }),
              },
              ...(body === undefined ? {} : { body }),
              redirect: "error",
              cache: "no-store",
              signal: controller.signal,
            });
            controller.signal.throwIfAborted();
            if (
              method === "POST" &&
              [400, 401, 403, 404, 409, 422, 429].includes(response.status)
            ) {
              state.writeMayHaveCommitted = false;
              void response.body?.cancel().catch(() => {});
              throw new DirectoryFault(
                response.status === 409
                  ? "conflict"
                  : response.status === 429
                    ? "limited"
                    : "rejected",
              );
            }
            if (
              response.status !== (method === "POST" ? 201 : 200) ||
              response.redirected ||
              (response.url && response.url !== url) ||
              !/^application\/json(?:\s*;|$)/i.test(
                response.headers.get("content-type") ?? "",
              )
            ) {
              void response.body?.cancel().catch(() => {});
              throw new DirectoryFault("unavailable");
            }
            return JSON.parse(
              new TextDecoder("utf-8", { fatal: true }).decode(
                await readBinaryBody(response, 65536, controller.signal),
              ),
            ) as unknown;
          };
          return work(send, state);
        })(),
        new Promise<never>((_resolve, reject) => {
          timer = setTimeout(() => {
            controller.abort();
            reject(Error("deadline"));
          }, this.timeoutMs);
        }),
      ]);
    } catch (error) {
      if (state.writeMayHaveCommitted)
        throw new AppError(
          "ACCOUNT_CREATION_UNCERTAIN",
          "Account creation could not be confirmed. Reconcile the directory before attempting another creation.",
          503,
        );
      const kind = error instanceof DirectoryFault ? error.kind : "unavailable";
      throw new AppError(
        kind === "conflict"
          ? "DIRECTORY_CONFLICT"
          : kind === "limited"
            ? "DIRECTORY_RATE_LIMITED"
            : kind === "rejected"
              ? "DIRECTORY_REJECTED"
              : "DIRECTORY_UNAVAILABLE",
        "Directory account details could not be verified.",
        kind === "conflict" ? 409 : kind === "limited" ? 429 : 503,
      );
    } finally {
      clearTimeout(timer);
      controller.abort();
    }
  }
  async findByEmail(
    value: string,
  ): Promise<Readonly<EntraDirectoryAccount> | null> {
    const email = this.email(value);
    const quote = (text: string) => text.replaceAll("'", "''");
    const url = new URL(graph);
    url.search = new URLSearchParams({
      $select: select,
      $top: "2",
      $filter: `identities/any(i:i/issuerAssignedId eq '${quote(email)}' and i/issuer eq '${this.issuer}')`,
    }).toString();
    return this.run(async (send) => {
      const result = z
        .object({
          value: z.array(z.unknown()).max(2),
          "@odata.nextLink": z.unknown().optional(),
        })
        .parse(await send(url.href, "GET"));
      if (result["@odata.nextLink"] !== undefined || result.value.length > 1)
        throw new DirectoryFault("conflict");
      return result.value.length === 0
        ? null
        : this.account(result.value[0], email);
    });
  }
  async getById(
    objectId: string,
    value: string,
  ): Promise<Readonly<EntraDirectoryAccount>> {
    const email = this.email(value);
    if (!z.uuid().safeParse(objectId).success)
      throw new AppError(
        "INVALID_DIRECTORY_REQUEST",
        "Enter valid account details.",
        422,
      );
    const id = objectId.toLowerCase(),
      url = new URL(`${graph}/${id}`);
    url.search = new URLSearchParams({ $select: select }).toString();
    return this.run(async (send) =>
      this.account(await send(url.href, "GET"), email, id),
    );
  }
  async createCustomer(
    value: string,
    displayName: string,
  ): Promise<Readonly<EntraDirectoryAccount>> {
    const email = this.email(value);
    if (
      typeof displayName !== "string" ||
      displayName !== displayName.trim() ||
      displayName.length < 1 ||
      displayName.length > 128 ||
      /[\u0000-\u001f\u007f]/.test(displayName)
    )
      throw new AppError(
        "INVALID_DIRECTORY_REQUEST",
        "Enter valid account details.",
        422,
      );
    return this.run(async (send) => {
      // This unknown bootstrap password is discarded, never returned or emailed.
      // Hosted SSPR/first-password behavior must be verified before runtime selection.
      const password = `Aa1!${randomBytes(32).toString("base64url")}`;
      const created = z.object({ id: z.uuid() }).parse(
        await send(
          graph,
          "POST",
          JSON.stringify({
            accountEnabled: true,
            displayName,
            identities: [
              {
                signInType: "emailAddress",
                issuer: this.issuer,
                issuerAssignedId: email,
              },
            ],
            mail: email,
            passwordProfile: {
              password,
              forceChangePasswordNextSignIn: true,
            },
            passwordPolicies: "DisablePasswordExpiration",
          }),
        ),
      );
      const id = created.id.toLowerCase(),
        url = new URL(`${graph}/${id}`);
      url.search = new URLSearchParams({ $select: select }).toString();
      return this.account(await send(url.href, "GET"), email, id);
    });
  }
}
